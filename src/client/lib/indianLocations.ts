/**
 * Real-time Postal Pincode Lookup targeting the official India Post open API
 * Resolves State, District, and Post Office names dynamically for any valid 6-digit Indian pincode.
 */
export const lookupPincode = async (pincode: string): Promise<PincodeLookupResult | null> => {
  const cleanPin = pincode.replace(/\D/g, '').trim();
  if (cleanPin.length !== 6) return null;

  try {
    const res = await fetch(`https://api.postalpincode.in/pincode/${cleanPin}`);
    if (!res.ok) return null;
    const data = await res.json();
    if (!data || !Array.isArray(data) || data.length === 0 || data[0].Status !== 'Success') {
      return null;
    }

    const postOffices = data[0].PostOffice || [];
    if (postOffices.length === 0) return null;

    const primaryPO = postOffices[0];
    const rawState = primaryPO.State || '';
    const rawDistrict = primaryPO.District || '';
    const city = primaryPO.Block && primaryPO.Block !== 'NA' ? primaryPO.Block : primaryPO.Name;

    // Match raw state with our standardized states
    let matchedState = rawState;
    const allStates = getIndianStates();
    const stateMatch = allStates.find(
      (s) => s.toLowerCase() === rawState.toLowerCase() || s.toLowerCase().includes(rawState.toLowerCase())
    );
    if (stateMatch) {
      matchedState = stateMatch;
    }

    // Match raw district with our standardized district list for that state
    let matchedDistrict = rawDistrict;
    const stateDistricts = getDistrictsByState(matchedState);
    const distMatch = stateDistricts.find(
      (d) => d.toLowerCase() === rawDistrict.toLowerCase() || d.toLowerCase().includes(rawDistrict.toLowerCase()) || rawDistrict.toLowerCase().includes(d.toLowerCase())
    );
    if (distMatch) {
      matchedDistrict = distMatch;
    }

    const poNames = Array.from(new Set(postOffices.map((po: any) => po.Name))).filter(Boolean) as string[];

    return {
      state: matchedState,
      district: matchedDistrict,
      city,
      postOffices: poNames,
    };
  } catch (err) {
    console.error('Error in realtime pincode lookup:', err);
    return null;
  }
};

