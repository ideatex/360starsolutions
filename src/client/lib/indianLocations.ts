export const getIndianStates = (): string[] => {
  return Object.keys(INDIAN_STATES_AND_DISTRICTS).sort();
};

export const getDistrictsByState = (state: string): string[] => {
  if (!state) return [];
  // Normalize match
  const match = Object.keys(INDIAN_STATES_AND_DISTRICTS).find(
    (k) => k.toLowerCase() === state.toLowerCase() || k.toLowerCase().includes(state.toLowerCase())
  );
  if (match && INDIAN_STATES_AND_DISTRICTS[match]) {
    return [...INDIAN_STATES_AND_DISTRICTS[match]].sort();
  }
  return [];
};

